// Writes static/admin/config.yml — the configuration of the editor, Sveltia
// CMS (a drop-in successor of Decap CMS) — from
// languages.json, so the editor and the site always know the same languages.
//
// Docusaurus keeps the default language's pages in docs/ and every other
// language's in i18n/<code>/docusaurus-plugin-content-docs/current/, so each
// language is its own collection in the editor.
//
//   CMS_REPO    owner/name of the repository       (Oleg-SIP/doc-softphone)
//   CMS_BRANCH  branch the editor commits to       (main)
//   CMS_AUTH    base URL of a GitHub OAuth proxy, for the Sign In with GitHub
//               button (see README); without it, sign in with a token
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const languages = JSON.parse(readFileSync(new URL('../languages.json', import.meta.url), 'utf8'));
const repo = process.env.CMS_REPO || 'Oleg-SIP/doc-softphone';
const branch = process.env.CMS_BRANCH || 'main';
const authBase = process.env.CMS_AUTH || '';
const site = (process.env.SITE_URL || 'https://docs.ai-softphone.com').replace(/^http:/, 'https:');
const base = (process.env.BASE_URL || '/').replace(/\/$/, '');

const [defaultLanguage] = languages;
const folderOf = (code) =>
  code === defaultLanguage.code ? 'docs' : `i18n/${code}/docusaurus-plugin-content-docs/current`;

const collection = ({ code, name }) => `  - name: docs_${code.replace('-', '_')}
    label: "${name} (${code})"
    label_singular: "${name}: page"
    folder: ${folderOf(code)}
    extension: md
    format: frontmatter
    create: true
    slug: "{{slug}}"
    nested:
      depth: 6
      summary: "{{title}}"
    meta:
      path: { widget: string, label: Path, index_file: index }
    fields:
      - { name: title, label: Title, widget: string }
      - { name: sidebar_label, label: Menu label, widget: string, required: false, hint: "Shown in the menu on the left; the title is used if empty" }
      - { name: sidebar_position, label: Menu position, widget: number, value_type: int, required: false }
      - { name: description, label: Description, widget: text, required: false }
      - { name: body, label: Text, widget: markdown }
`;

const yaml = `# GENERATED by scripts/gen-cms-config.mjs — edit languages.json or the script.
backend:
  name: github
  repo: ${repo}
  branch: ${branch}${authBase ? `\n  base_url: ${authBase}` : ''}

site_url: ${site}${base}/
display_url: ${site}${base}/
logo:
  src: ${site}${base}/img/logo.svg

media_folder: static/img/docs
public_folder: /img/docs

collections:
${languages.map(collection).join('')}`;

mkdirSync(new URL('../static/admin/', import.meta.url), { recursive: true });
writeFileSync(new URL('../static/admin/config.yml', import.meta.url), yaml);
console.log(`static/admin/config.yml: ${languages.length} languages, ${repo}@${branch}`);
